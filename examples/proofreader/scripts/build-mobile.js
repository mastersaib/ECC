#!/usr/bin/env node
'use strict';

/**
 * Build the web bundle the Android (and later iOS) app ships, in mobile/www.
 *
 * Differences from public/:
 *   - fonts are bundled (OFL-licensed @fontsource files) instead of loaded
 *     from Google, so the app makes no third-party requests and works offline
 *   - the service worker and web manifest are left out (the app shell is
 *     already on the device)
 *   - the official Anthropic SDK is bundled into vendor/anthropic-sdk.js for
 *     the on-device AI check
 *
 *   node scripts/build-mobile.js     # then: npx cap sync android
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const PUBLIC_DIR = path.join(ROOT, 'public');
const OUT = path.join(ROOT, 'mobile', 'www');
const SKIP = new Set(['sw.js', 'manifest.webmanifest', path.join('js', 'offline.js'), 'vendor']);
const FONTS = [
  { pkg: '@fontsource/literata', sheets: ['400.css', '600.css', '400-italic.css'] },
  { pkg: '@fontsource/source-sans-3', sheets: ['400.css', '600.css', '700.css'] },
  { pkg: '@fontsource/ibm-plex-mono', sheets: ['400.css', '500.css'] }
];
const SUBSETS = /-(latin|latin-ext)-\d+-(normal|italic)\.woff2/;

// The bundle's only network destination is Anthropic's API, for the AI check.
// Capacitor injects its bridge script right after <head>, before this policy
// takes effect, so script-src can stay 'self'.
const CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  "font-src 'self'",
  "img-src 'self' data: blob:",
  "connect-src 'self' https://api.anthropic.com",
  "object-src 'none'",
  "base-uri 'none'"
].join('; ');

// Shown by Capacitor (server.errorPath) when the phone's WebView is older than
// android.minWebViewVersion. Plain HTML: an old WebView cannot run the app.
const OLD_WEBVIEW_PAGE = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Update Android System WebView</title>
<style>
  body { font: 17px/1.5 sans-serif; margin: 0; padding: 32px 24px; background: #EEF1F5; color: #1A2230; }
  h1 { font-size: 22px; margin: 0 0 12px; }
  @media (prefers-color-scheme: dark) { body { background: #0E1319; color: #E6EAF0; } }
</style>
</head>
<body>
<h1>Galley needs a newer WebView</h1>
<p>This phone's Android System WebView is too old to run Galley. Open Google Play, search for <strong>Android System WebView</strong> (or <strong>Chrome</strong> on Android 7 to 9), update it, then open Galley again.</p>
</body>
</html>
`;

function copyTree(from, to, rel) {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const relPath = rel ? path.join(rel, entry.name) : entry.name;
    if (SKIP.has(relPath)) continue;
    const src = path.join(from, entry.name);
    const dest = path.join(to, entry.name);
    if (entry.isDirectory()) copyTree(src, dest, relPath);
    else fs.copyFileSync(src, dest);
  }
}

/** Keep the latin and latin-ext faces of each sheet, pointing at local files. */
function buildFonts() {
  const fontDir = path.join(OUT, 'fonts');
  fs.mkdirSync(fontDir, { recursive: true });
  const css = ['/* Bundled from @fontsource (SIL Open Font License 1.1). Generated by scripts/build-mobile.js. */'];
  for (const { pkg, sheets } of FONTS) {
    const pkgDir = path.dirname(require.resolve(`${pkg}/package.json`));
    for (const sheet of sheets) {
      const source = fs.readFileSync(path.join(pkgDir, sheet), 'utf8');
      for (const block of source.match(/@font-face\s*{[^}]*}/g) || []) {
        const file = (block.match(/url\(\.\/files\/([^)]+\.woff2)\)/) || [])[1];
        if (!file || !SUBSETS.test(file)) continue;
        fs.copyFileSync(path.join(pkgDir, 'files', file), path.join(fontDir, file));
        css.push(block.replace(/src:[^;]+;/, `src: url(${file}) format('woff2');`));
      }
    }
    const license = path.join(pkgDir, 'LICENSE');
    if (fs.existsSync(license)) fs.copyFileSync(license, path.join(fontDir, `LICENSE-${path.basename(pkg)}.txt`));
  }
  fs.writeFileSync(path.join(fontDir, 'fonts.css'), `${css.join('\n\n')}\n`);
}

function buildIndex() {
  const file = path.join(OUT, 'index.html');
  let html = fs.readFileSync(file, 'utf8');
  html = html.replace(/<!-- local:start -->[\s\S]*?<!-- local:end -->\n?/g, '');
  html = html.replace(/<link rel="preconnect"[^>]*>\n?/g, '');
  html = html.replace(/<link rel="stylesheet" href="https:\/\/fonts\.googleapis\.com[^>]*>/, '<link rel="stylesheet" href="fonts/fonts.css">');
  if (/fonts\.googleapis|sw\.js|offline\.js/.test(html)) throw new Error('index.html still references web-only resources');
  if (!html.includes('<head>\n<meta charset="utf-8">')) throw new Error('index.html must start its head with <meta charset> for the CSP');
  html = html.replace('<head>\n<meta charset="utf-8">', `<head>\n<meta charset="utf-8">\n<meta http-equiv="Content-Security-Policy" content="${CSP}">`);
  fs.writeFileSync(file, html);
  fs.writeFileSync(path.join(OUT, 'update-webview.html'), OLD_WEBVIEW_PAGE);
}

async function buildSdk() {
  const esbuild = require('esbuild');
  await esbuild.build({
    stdin: {
      contents: "const mod = require('@anthropic-ai/sdk'); module.exports = mod.default || mod;",
      resolveDir: ROOT,
      sourcefile: 'anthropic-sdk-entry.js'
    },
    bundle: true,
    format: 'iife',
    globalName: 'AnthropicSDK',
    platform: 'browser',
    target: ['chrome100', 'safari15'],
    minify: true,
    legalComments: 'eof',
    outfile: path.join(OUT, 'vendor', 'anthropic-sdk.js')
  });
}

async function main() {
  fs.rmSync(OUT, { recursive: true, force: true });
  copyTree(PUBLIC_DIR, OUT, '');
  buildFonts();
  buildIndex();
  await buildSdk();
  const size = dir => fs.readdirSync(dir, { withFileTypes: true })
    .reduce((sum, e) => sum + (e.isDirectory() ? size(path.join(dir, e.name)) : fs.statSync(path.join(dir, e.name)).size), 0);
  console.log(`Wrote ${path.relative(process.cwd(), OUT)} (${Math.round(size(OUT) / 1024)} KB)`);
}

if (require.main === module) {
  main().catch(err => {
    console.error(err.message);
    process.exit(1);
  });
}

module.exports = { main, OUT, CSP };
